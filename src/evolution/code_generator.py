"""Gerador automático de código."""

from typing import Dict, Any, Optional, List
from datetime import datetime
import ast


class CodeGenerator:
    """
    Gera código automaticamente.
    
    Responsabilidades:
    - Gerar código Python a partir de descrições
    - Criar novos módulos
    - Gerar funções e classes
    - Validar código gerado
    """
    
    def __init__(self, evolution_manager):
        self.evolution_manager = evolution_manager
        self.logger = evolution_manager.logger
    
    async def generate(self, description: str, module: str = "general") -> Dict[str, Any]:
        """
        Gera código a partir de uma descrição.
        """
        self.logger.info(f"Gerando código para: {description[:50]}...")
        
        result = {
            "success": False,
            "description": description,
            "module": module,
            "code": "",
            "files": [],
            "timestamp": datetime.now().isoformat()
        }
        
        # 1. Analisa a descrição
        intent = self._analyze_intent(description)
        
        # 2. Gera código apropriado
        if intent == "function":
            code = self._generate_function(description)
        elif intent == "class":
            code = self._generate_class(description)
        elif intent == "module":
            code = self._generate_module(description)
        elif intent == "tool":
            code = self._generate_tool(description)
        else:
            code = self._generate_general(description)
        
        # 3. Valida código
        if code and self._validate_code(code):
            result["code"] = code
            result["success"] = True
            
            # Determina arquivo
            file_path = f"src/auto_generated/{module}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.py"
            result["files"].append(file_path)
            
            self.logger.info(f"Código gerado com sucesso: {file_path}")
        else:
            self.logger.warning("Falha na validação do código gerado")
        
        return result
    
    def _analyze_intent(self, description: str) -> str:
        """
        Analisa a intenção da descrição.
        """
        desc_lower = description.lower()
        
        if "função" in desc_lower or "function" in desc_lower:
            return "function"
        elif "classe" in desc_lower or "class" in desc_lower:
            return "class"
        elif "módulo" in desc_lower or "module" in desc_lower:
            return "module"
        elif "ferramenta" in desc_lower or "tool" in desc_lower:
            return "tool"
        else:
            return "general"
    
    def _generate_function(self, description: str) -> str:
        """Gera uma função."""
        # Extrai nome (simples)
        words = description.split()
        name = "generated_function"
        for i, word in enumerate(words):
            if word in ["função", "function", "criar", "create"]:
                if i + 1 < len(words):
                    name = words[i + 1].lower().replace("(", "").replace(")", "")
                    break
        
        code = f'''
def {name}():
    """
    {description}
    
    Generated by EVA Evolution System
    """
    pass
'''
        return code
    
    def _generate_class(self, description: str) -> str:
        """Gera uma classe."""
        words = description.split()
        name = "GeneratedClass"
        for i, word in enumerate(words):
            if word in ["classe", "class"]:
                if i + 1 < len(words):
                    name = words[i + 1].capitalize()
                    break
        
        code = f'''
class {name}:
    """
    {description}
    
    Generated by EVA Evolution System
    """
    
    def __init__(self):
        pass
    
    def process(self, data):
        return data
'''
        return code
    
    def _generate_module(self, description: str) -> str:
        """Gera um módulo."""
        code = f'''
"""
{description}

Generated by EVA Evolution System
"""

from typing import Dict, Any, Optional


def main():
    pass


if __name__ == "__main__":
    main()
'''
        return code
    
    def _generate_tool(self, description: str) -> str:
        """Gera uma ferramenta."""
        words = description.split()
        name = "GeneratedTool"
        for i, word in enumerate(words):
            if word in ["tool", "ferramenta"]:
                if i + 1 < len(words):
                    name = words[i + 1].capitalize()
                    break
        
        code = f'''
from src.tools.base_tool import BaseTool


class {name}(BaseTool):
    """
    {description}
    
    Generated by EVA Evolution System
    """
    
    def get_info(self) -> Dict[str, Any]:
        return {{
            "name": "{name.lower()}",
            "description": "{description}",
            "capabilities": ["generated"]
        }}
    
    def get_required_params(self) -> List[str]:
        return []
    
    def validate(self, params: Dict[str, Any]) -> bool:
        return True
    
    async def execute(self, params: Dict[str, Any], context: Dict[str, Any] = None) -> Dict[str, Any]:
        return {{
            "success": True,
            "result": "Ferramenta gerada executada",
            "params": params
        }}
'''
        return code
    
    def _generate_general(self, description: str) -> str:
        """Gera código geral."""
        code = f'''
"""
{description}

Generated by EVA Evolution System
"""


def process(data):
    """Processa dados."""
    return data
'''
        return code
    
    def _validate_code(self, code: str) -> bool:
        """
        Valida código Python.
        """
        try:
            ast.parse(code)
            return True
        except SyntaxError as e:
            self.logger.error(f"Erro de sintaxe no código gerado: {e}")
            return False